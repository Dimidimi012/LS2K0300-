/*********************************************************************************************************************
 * LS2K0300 智能车 巡线工程 —— 全局参数配置
 * 适用平台   LS2K0300（逐飞 2K300 核心板 + 逐飞主板）
 * 硬件结构   后轮双电机差速驱动（DRV8701E 双电机驱动板），无舵机
 * 视觉方案   传统图像处理巡线（UVC 摄像头 160x120，灰度 + 大津二值化 + 逐行找边线）
 *
 * 使用说明   所有需要在实车上标定的参数全部集中在本文件，按注释逐项调整即可。
 *            标定顺序建议：电机方向 -> 编码器方向/齿比 -> 二值化阈值 -> 偏差方向 -> 方向环KP -> 速度
 ********************************************************************************************************************/
#ifndef __CONFIG_HPP__
#define __CONFIG_HPP__

#include "zf_common_typedef.hpp"

/* =====================================================================
 * 一、图像处理参数
 * ===================================================================== */
// 摄像头分辨率（与 libraries/zf_device/zf_device_uvc.hpp 中 UVC_WIDTH/UVC_HEIGHT 保持一致）
#define IMG_W               160     // 图像宽
#define IMG_H               120     // 图像高
#define IMG_CENTER_X        (IMG_W / 2)   // 图像横向中心（偏差参考点）

// 二值化：1 = 白色为赛道/引导线（浅色赛道深色背景），0 = 黑色为赛道（深色赛道浅色背景）
#define LINE_IS_WHITE       1

// 阈值模式：0 = 固定阈值（用 FIXED_THRESHOLD），1 = 大津自适应阈值
#define USE_OTSU            1
#define FIXED_THRESHOLD     100     // USE_OTSU=0 时生效

// 预处理：高斯滤波核（奇数，0 表示不做滤波）
#define GAUSS_KERNEL        3

// ROI：参与巡线的行范围（图像第0行为最远端，第IMG_H-1行为车头最近端）
// 近端留出靠近车头的盲区行（车头/底盘可能入画），远端裁剪掉不可用区域
#define ROI_ROW_BOTTOM      (IMG_H - 1)   // 近端起始行（从下往上扫）
#define ROI_ROW_TOP         (IMG_H - 45)  // 远端截止行（45 行以上视野太远、赛道太窄，不做处理）

// 找线搜索窗口半径（像素）：以"上一行中线"为中心向左右各扩展该宽度进行搜索
#define SEARCH_HALF         30

// 每行允许的赛道最小白像素宽度（像素），小于该宽度视为噪声丢线
#define MIN_LINE_WIDTH      4

// 单边丢线时推算赛宽：1 = 使用上一行实际赛宽，0 = 使用标准赛宽表
#define USE_PREV_WIDE       1
// USE_PREV_WIDE=0 时的标准赛宽（像素，近端直线赛道实测标定）
#define STD_ROAD_WIDE       36

// 偏差计算：取近端若干行的中线偏差做加权平均（值越大越贴近近端决策）
#define ERROR_ROWS          22      // 参与偏差计算的行数（从 ROI_ROW_BOTTOM 向上取）
#define ERROR_NEAR_WEIGHT   2.0f    // 近端行权重倍率（>1 近端权重更大，弯道响应更快）

/* =====================================================================
 * 二、方向环（转向）PID —— 输入：图像偏差(像素)  输出：差速控制量
 * ===================================================================== */
#define STEER_KP            0.6f    // 比例系数（先给一个保守值，实车逐步加大）
#define STEER_KI            0.0f    // 积分（差速车一般不需要，防止低速打摆）
#define STEER_KD            0.4f    // 微分系数（抑制震荡，弯道提速后加大）
#define STEER_OUT_LIMIT     22      // 差速输出限幅（PWM 占空比单位，与电机占空比同量纲）
// 偏差符号：1 = 赛道中线偏右(error>0)时车右转（右轮减、左轮加），反之为 -1
#define STEER_DIR           1

// 方向环运行频率系数：图像帧率不固定，用 dt 归一化微分项（见 main.cpp）
#define STEER_DT_NORM       0.03f   // 参考控制周期(秒)，实际按帧间隔折算

/* =====================================================================
 * 三、速度控制
 * ===================================================================== */
// 速度闭环开关：1 = 编码器 + 速度PID 闭环；0 = 开环（直接给固定占空比）
#define SPEED_CLOSED_LOOP 1

// 开环模式下的基础占空比（0~MOTOR_DUTY_MAX，占空比百分数）
#define OPEN_LOOP_DUTY      25

// 闭环模式下的目标速度（m/s），起步建议 0.3~0.5，调稳后逐步加到 1.0+
#define SPEED_TARGET_MPS    0.6f

// 速度PID（增量式，输出为 PWM 占空比百分数）
#define SPEED_KP            0.8f
#define SPEED_KI            0.15f
#define SPEED_KD            0.0f
#define SPEED_OUT_LIMIT     40      // 速度环输出上限（%）

/* =====================================================================
 * 四、电机参数（DRV8701E 双电机驱动：PWM + DIR）
 * ===================================================================== */
// PWM 占空比最大值百分数（%）：防止起步全速、保护电机，实车标定
#define MOTOR_DUTY_MAX      40

// 电机方向符号：1 = 正占空比前进（DIR=1 前进）；若实测反了改为 -1
#define MOTOR_DIR_L         -1
#define MOTOR_DIR_R         1

// 差速分配方式固定为：left = base + steer（内弯侧减、外弯侧加），右轮对称。
// 若实测转向反了，将 STEER_DIR 取反即可，一般无需改动此处。

/* =====================================================================
 * 五、编码器参数
 * ===================================================================== */
#define PULSE_PER_REV       2048    // 编码器每转脉冲数（正交编码器，按实际编码器改）
#define WHEEL_CIRCUMFERENCE 0.1957f // 车轮周长（米）
#define GEAR_RATIO          2.267f  // 电机轴:车轮轴 齿比（68/30 电机端 68 齿 : 车轮端 30 齿）
// 编码器方向：1 = 前进时计数值为正；若实测反了改为 -1（左右分别配置）
#define ENCODER_DIR_L       1
#define ENCODER_DIR_R       -1      // 右轮编码器通常镜像安装，实测确认

/* =====================================================================
 * 六、丢线保护
 * ===================================================================== */
// 双边丢线连续超过该帧数（约 = 秒数*帧率）后停车保护
#define LOST_STOP_FRAMES    60

/* =====================================================================
 * 七、调试输出
 * ===================================================================== */
#define DEBUG_PRINT         1       // 串口打印开关（偏差/速度/丢线）
#define DEBUG_PRINT_FREQ    20      // 每 N 帧打印一次

// 逐飞助手 TCP 图像回传（0=关闭 1=开启）：用于上位机看灰度图与边线，调参阶段建议开
#define TCP_DEBUG           0
#define TCP_SERVER_IP       "192.168.43.58"   // 电脑 IP（逐飞助手 TCP Server 地址）
#define TCP_PORT            8086

#endif // __CONFIG_HPP__
